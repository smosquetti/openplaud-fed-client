/**
 * Builds public/openplaud.js — the self-contained chat bubble:
 * Strophe 5.0.0 (MIT) inlined as a plain script + bubble/openplaud.js source.
 * The UMD build sets globalThis.Strophe, which the bubble IIFE consumes.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const strophePath = path.join(root, 'node_modules/strophe.js/dist/strophe.umd.min.js');
const bubblePath = path.join(root, 'bubble/openplaud.js');
const outPath = path.join(root, 'public/openplaud.js');

let strophe;
let bubble;
try {
  strophe = readFileSync(strophePath, 'utf8');
  bubble = readFileSync(bubblePath, 'utf8');
} catch (err) {
  console.error(`build-bubble: missing input (${err.message}).`);
  console.error('Is strophe.js installed? Run: npm install');
  process.exit(1);
}

const banner = `/*
 * OpenPlaud customer chat bubble — self-contained single-file build.
 * Generated by scripts/build-bubble.mjs — do not edit; edit
 * bubble/openplaud.js (and the Strophe version) and rebuild.
 * Contains: Strophe 5.0.0 (MIT license, inlined UMD build) + bubble source.
 *
 * Embed: <script src="/openplaud.js"></script>
 */
`;

mkdirSync(path.dirname(outPath), { recursive: true });
const output = banner + strophe + '\n' + bubble;
writeFileSync(outPath, output);
console.log(`Wrote ${path.relative(root, outPath)} (${output.length} chars)`);
